#!/usr/bin/env python3
"""Pack the system images for the cartridge and write the boot load table.

Usage: mkimage.py OUT.bin OUT.inc FILE@ADDR [FILE@ADDR ...]

Each FILE is a binary to be loaded at the C64 address ADDR (hex). The
images are concatenated into OUT.bin (ROM banks 1 and up, copied to REU
$020000 at boot) and OUT.inc gets the load table for src/boot/boot.s:
IMG_BANKS (number of 8 KB ROM banks), IMG_COUNT and per image the REU
address, C64 address and length.
"""
import sys

REU_BASE = 0x020000
BANK = 0x2000


def main(argv):
    if len(argv) < 4:
        sys.exit(__doc__)
    blob = bytearray()
    rows = []
    for arg in argv[3:]:
        path, addr = arg.rsplit("@", 1)
        data = open(path, "rb").read()
        if not 0 < len(data) <= 0x10000:
            sys.exit("%s: size %d not 1..65536" % (path, len(data)))
        rows.append((REU_BASE + len(blob), int(addr, 16), len(data)))
        blob += data
    banks = (len(blob) + BANK - 1) // BANK
    blob = blob.ljust(banks * BANK, b"\xff")
    open(argv[1], "wb").write(blob)
    inc = ["; Generated by tools/mkimage.py",
           "IMG_BANKS = %d" % banks,
           "IMG_COUNT = %d" % len(rows),
           ".macro IMG_TABLE"]
    for reu, c64, length in rows:
        inc.append("        .faraddr $%06X" % reu)
        inc.append("        .word $%04X, $%04X" % (c64, length & 0xFFFF))
    inc.append(".endmacro")
    open(argv[2], "w").write("\n".join(inc) + "\n")


if __name__ == "__main__":
    main(sys.argv)
