#!/usr/bin/env python3
"""Pack the system images for the cartridge and write the boot load table.

Usage: mkimage.py [--cpu N] OUT.bin OUT.inc FILE@ADDR [FILE@ADDR ...]

FILE@REU puts FILE at the start of the image (REU $020000 at run time)
without a load table row: data the kernal fetches itself (the overlay
modules, src/kernal/overlay.s). At most one, before the others.
FILE@BANKn puts FILE at the start of REU bank n (hex), padding up to it, also
without a load table row: the system drive (drive E), which the kernal
reads as an REU drive from that bank.

Each FILE is a binary to be loaded at the C64 address ADDR (hex). The
images are concatenated into OUT.bin (ROM banks 1 and up, copied to REU
$020000 at boot) and OUT.inc gets the load table for src/boot/boot.s:
IMG_BANKS (number of 8 KB ROM banks), IMG_COUNT and per image the REU
address, C64 address and length. The first N images (--cpu N, IMG_CPU)
are copied by the CPU straight from the cartridge ROM before the REU is
used (the boot splash); their ROM bank and offset follow from the REU
address ($020000 = bank 1, offset 0).
"""
import sys

REU_BASE = 0x020000
BANK = 0x2000


def main(argv):
    cpu = 0
    if argv[1:2] == ["--cpu"]:
        cpu = int(argv[2])
        argv = argv[:1] + argv[3:]
    if len(argv) < 4:
        sys.exit(__doc__)
    blob = bytearray()
    rows = []
    for arg in argv[3:]:
        path, addr = arg.rsplit("@", 1)
        data = open(path, "rb").read()
        if addr.upper() == "REU":
            if blob:
                sys.exit("%s: an REU-only image must come first" % path)
            blob += data
            continue
        if addr.upper().startswith("BANK"):
            at = (int(addr[4:], 16) << 16) - REU_BASE
            if at < len(blob):
                sys.exit("%s: bank %s is already used (image up to $%06X)"
                         % (path, addr[4:], REU_BASE + len(blob)))
            blob += b"\xff" * (at - len(blob)) + data
            continue
        if not 0 < len(data) <= 0x10000:
            sys.exit("%s: size %d not 1..65536" % (path, len(data)))
        rows.append((REU_BASE + len(blob), int(addr, 16), len(data)))
        blob += data
    banks = (len(blob) + BANK - 1) // BANK
    blob = blob.ljust(banks * BANK, b"\xff")
    open(argv[1], "wb").write(blob)
    inc = ["; Generated by tools/mkimage.py",
           "IMG_BANKS = %d" % banks,
           "IMG_COUNT = %d" % len(rows),
           "IMG_CPU = %d" % cpu,
           ".macro IMG_TABLE"]
    for reu, c64, length in rows:
        inc.append("        .faraddr $%06X" % reu)
        inc.append("        .word $%04X, $%04X" % (c64, length & 0xFFFF))
    inc.append(".endmacro")
    open(argv[2], "w").write("\n".join(inc) + "\n")


if __name__ == "__main__":
    main(sys.argv)
