def rows(*lines, start=0):
    return dict((start + i, l) for i, l in enumerate(lines))


def same(line, first, last):
    return dict((r, line) for r in range(first, last + 1))


def merge(*parts):
    out = {}
    for p in parts:
        out.update(p)
    return out


