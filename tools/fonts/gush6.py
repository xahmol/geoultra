CURSOR = ["######"] * 8          # 127: the cursor, the whole cell


def glyph_bytes(rows, width=5):
    out = []
    for r in range(8):
        line = rows[r] if r < len(rows) else "." * width
        assert len(line) == width, (rows, line)
        v = 0
        for i, ch in enumerate(line):
            if ch == "#":
                v |= 0x80 >> i
        out.append(v)
    return out


def main():
    assert len(G) == 95, len(G)
    data = []
    for code in range(32, 127):
        data += glyph_bytes(G[chr(code)])
    data += glyph_bytes(CURSOR, 6)
    with open(sys.argv[1], "w") as f:
        f.write("; gush's console font (tools/fonts/gush6.py; generated, do not edit):\n"
                "; ASCII 32-126 and the cursor at 127, 8 bytes each, pixels in bits 7-2.\n")
        for i in range(0, len(data), 8):
            f.write("        .byte " + ", ".join("$%02X" % b for b in data[i:i + 8]) + "\n")


if __name__ == "__main__":
    main()
