def rows(art):
    lines = [ln for ln in art.strip("\n").split("\n")]
    assert len(lines) == 21, len(lines)
    for ln in lines:
        assert len(ln) == 24, ln
    return lines


def packet(art):
    out = [0xBF]
    for ln in rows(art):
        for c in range(3):
            b = 0
            for ch in ln[c * 8:c * 8 + 8]:
                b = b << 1 | (ch == "#")
            out.append(b)
    return out + [0]


def main(argv):
    if len(argv) == 3 and argv[1] == "--png":
        from PIL import Image
        scale, gap = 4, 8
        im = Image.new("RGB", (len(ICONS) * (24 * scale + gap) + gap, 21 * scale + 2 * gap), (178, 178, 178))
        for n, (name, art) in enumerate(ICONS):
            for y, ln in enumerate(rows(art)):
                for x, ch in enumerate(ln):
                    if ch == "#":
                        for dy in range(scale):
                            for dx in range(scale):
                                im.putpixel((gap + n * (24 * scale + gap) + x * scale + dx,
                                             gap + y * scale + dy), (74, 74, 74))
        im.save(argv[2])
        return
    if len(argv) != 2:
        sys.exit(__doc__)
    lines = ["; Generated by tools/mkbigicons.py: the icon view's generic icons",
             "BIG_N = %d" % len(ICONS)]
    for n, (name, _) in enumerate(ICONS):
        lines.append("BIG_%s = %d" % (name, n))
    lines.append("BigIcons:")
    for name, art in ICONS:
        data = packet(art)
        lines.append("        ; %s" % name.lower())
        for i in range(0, 64, 16):
            lines.append("        .byte " + ", ".join("$%02X" % b for b in data[i:i + 16]))
    open(argv[1], "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv)
