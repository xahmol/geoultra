#!/usr/bin/env python3
"""Draw GeoUltra's dialog box system icons and write them as ca65 source.

Usage: mkicons.py OUT.s
       mkicons.py --icon OUT.inc NAME LABEL [WIDTH]
                                             (one more button in the same
                                              style, for a program's own
                                              dialog: NAME: and its data;
                                              WIDTH in pixels, a multiple
                                              of 8, default 48)

GeoUltra's own design (no Berkeley artwork): 48 x 16 buttons (the GEOS
system icon size, 6 cards x 16 lines), a frame with rounded corners and a
2-pixel shadow right and below, and the label in bold in GeoUltra's
system font, centred by its measured width. Output: one compacted bitmap
(GEOS compacted bitmap format) per icon, labels SysIconOK .. SysIconDISK,
in the order of the icon numbers OK (1) .. DISK (6).
"""
import importlib.util
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
W, H = 48, 16
LABELS = [("OK", "OK"), ("CANCEL", "Cancel"), ("YES", "Yes"), ("NO", "No"),
          ("OPEN", "Open"), ("DISK", "Disk")]


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


font = load(os.path.join(ROOT, "tools", "fonts", "system9.py"), "system9")


def icon(label, W=W):
    pix = [[0] * W for _ in range(H)]

    def put(x, y, v=1):
        if 0 <= x < W and 0 <= y < H:
            pix[y][x] = v
    fw, fh = W - 2, H - 2                       # frame; the shadow takes 2
    for x in range(fw):
        put(x, 0)
        put(x, fh - 1)
    for y in range(fh):
        put(0, y)
        put(fw - 1, y)
    for x, y in ((0, 0), (fw - 1, 0), (0, fh - 1), (fw - 1, fh - 1)):
        put(x, y, 0)                            # rounded corners
    for y in range(2, H):                       # shadow right
        put(fw, y)
        put(fw + 1, y)
    for x in range(2, W):                       # shadow below
        put(x, fh)
        put(x, fh + 1)
    # bold label (each character one pixel wider), centred in the frame
    width = sum(font.WIDTHS[ord(c) - 32] + 1 for c in label)
    if width + 2 > fw - 2:
        sys.exit("mkicons.py: \"%s\" (%d pixels) does not fit a %d-pixel button"
                 % (label, width, W))
    x = (fw - width) // 2
    cap = font.BASELINE + 1                     # rows 0..baseline: cap height
    top = 1 + (fh - 2 - cap) // 2               # caps centred inside the frame
    for c in label:
        for row, ink in font.GLYPHS[c].items():
            for col, ch in enumerate(ink):
                if ch == "#":
                    put(x + 1 + col, top + row)
                    put(x + 2 + col, top + row)
        x += font.WIDTHS[ord(c) - 32] + 1
    out = []
    for y in range(H):
        for cx in range(W // 8):
            byte = 0
            for b in range(8):
                byte = byte << 1 | pix[y][cx * 8 + b]
            out.append(byte)
    return out


def compact(data):
    """GEOS compacted bitmap: repeats of 3 or more as repeat packets
    (up to 127), the rest as unique packets (up to 91 bytes)."""
    out, i, unique = [], 0, []

    def flush():
        while unique:
            part = unique[:91]
            del unique[:91]
            out.extend([128 + len(part)] + part)
    while i < len(data):
        run = 1
        while i + run < len(data) and data[i + run] == data[i] and run < 127:
            run += 1
        if run >= 3:
            flush()
            out.extend([run, data[i]])
            i += run
        else:
            unique.append(data[i])
            i += 1
    flush()
    return out


def main(argv):
    if len(argv) in (5, 6) and argv[1] == "--icon":
        width = int(argv[5]) if len(argv) == 6 else W
        if width % 8 or not 16 <= width <= 320:
            sys.exit("mkicons.py: WIDTH must be a multiple of 8 (16-320)")
        data = compact(icon(argv[4], width))
        lines = ["; Generated by tools/dev/mkicons.py: the button \"%s\"" % argv[4], "%s:" % argv[3]]
        for i in range(0, len(data), 16):
            lines.append("        .byte " + ", ".join("$%02X" % b for b in data[i:i + 16]))
        open(argv[2], "w").write("\n".join(lines) + "\n")
        return
    if len(argv) != 2:
        sys.exit(__doc__)
    lines = ["; Generated by tools/dev/mkicons.py: GeoUltra's dialog box system icons",
             "        .export SysIconOK, SysIconCANCEL, SysIconYES, SysIconNO",
             "        .export SysIconOPEN, SysIconDISK",
             '        .segment "RODATA"']
    for name, label in LABELS:
        data = compact(icon(label))
        lines.append("SysIcon%s:" % name)
        for i in range(0, len(data), 16):
            lines.append("        .byte " + ", ".join("$%02X" % b for b in data[i:i + 16]))
    open(argv[1], "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv)
