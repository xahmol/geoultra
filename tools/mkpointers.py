#!/usr/bin/env python3
"""The mouse pointer's designs (docs/SETTINGS.md, the Pointer page): four
own drawings as hi-res sprites (24 x 21), written as ca65 source.

Usage: mkpointers.py OUT.inc

Each design is text art below ("#" a set pixel, "H" a set pixel that is
also the hot spot, "h" an unset hot spot): the hot spot is the pixel the
mouse position points at; the kernal places the sprite so that pixel is
at the mouse (src/kernal/pointer.s). Output: Pointers (4 x 63 bytes, in
the order of the Pointer page) and PointerHot (x, y per design).
GeoUltra's own design.
"""
import sys

DESIGNS = [
    ("classic arrow", """
H#
###
####
#####
######
#######
#####
##.##
#...##
....##
.....##
.....##
"""),
    ("large arrow", """
H
##
###
####
#####
######
#######
########
#########
##########
###########
############
#######
###.###
##..###
#....###
.....###
......###
......###
"""),
    ("hand", """
....H
...###
...###
...###
...###
...######
...#########
.#.##########
#############
#############
#############
.############
..##########
..##########
...########
...########
"""),
    ("crosshair", """
.......#
.......#
.......#
.......#
.......#
.......#
.......
######.h.######
.......
.......#
.......#
.......#
.......#
.......#
.......#
"""),
]

W, H = 24, 21


def design(name, art):
    rows = art.strip("\n").split("\n")
    assert len(rows) <= H, name
    bits = [[0] * W for _ in range(H)]
    hot = None
    for y, row in enumerate(rows):
        assert len(row) <= W, (name, y)
        for x, c in enumerate(row):
            if c in "#H":
                bits[y][x] = 1
            if c in "Hh":
                assert hot is None, name
                hot = (x, y)
            assert c in "#Hh. ", (name, c)
    assert hot is not None, name
    data = []
    for y in range(H):
        for b in range(3):
            v = 0
            for i in range(8):
                v = v << 1 | bits[y][b * 8 + i]
            data.append(v)
    return data, hot


def main():
    out = ["; Generated by tools/mkpointers.py: the mouse pointer's designs",
           "; (own drawings; the Pointer page's order)", "Pointers:"]
    hots = []
    for name, art in DESIGNS:
        data, hot = design(name, art)
        hots.append(hot)
        out.append("        ; %s, hot spot %d, %d" % (name, hot[0], hot[1]))
        for i in range(0, 63, 21):
            out.append("        .byte " + ", ".join("$%02X" % v for v in data[i:i + 21]))
    out.append("PointerHot:")
    for x, y in hots:
        out.append("        .byte %d, %d" % (x, y))
    out.append("POINTERS_N = %d" % len(DESIGNS))
    open(sys.argv[1], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
