#!/usr/bin/env python3
"""Build a GEOS font (header, index table, bitstream) as ca65 source.

Usage: mkfont.py FONTSOURCE.py OUT.s LABEL

GEOS font layout (HG2G2022, "Fonts"): header of 8 bytes (baseline
offset, set width in bytes, height, offset of the index table, offset of
the bitstream), an index table of 97 words (pixel offset of characters
32..127 and the end), then the bitstream: `height` rows of `set width`
bytes, characters side by side, most significant bit first.
"""
import importlib.util
import os
import sys


def load(path):
    spec = importlib.util.spec_from_file_location("font", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def build(font):
    widths, height = font.WIDTHS, font.HEIGHT
    if len(widths) != 96:
        sys.exit("need 96 widths")
    offsets = [0]
    for w in widths:
        offsets.append(offsets[-1] + w)
    set_width = max((offsets[-1] + 7) // 8, getattr(font, "SET_WIDTH", 0))
    bits = [[0] * (set_width * 8) for _ in range(height)]
    for code in range(32, 128):
        ch = chr(code)
        if ch not in font.GLYPHS:
            sys.exit("glyph %r missing" % ch)
        width = widths[code - 32]
        for row, ink in font.GLYPHS[ch].items():
            if not 0 <= row < height:
                sys.exit("glyph %r: row %d outside the font" % (ch, row))
            if len(ink) > width - 1:
                sys.exit("glyph %r row %d: %d columns, width allows %d"
                         % (ch, row, len(ink), width - 1))
            for col, c in enumerate(ink):
                if c == "#":
                    bits[row][offsets[code - 32] + 1 + col] = 1
    data = bytearray()
    for row in bits:
        for i in range(set_width):
            byte = 0
            for b in row[i * 8:i * 8 + 8]:
                byte = byte << 1 | b
            data.append(byte)
    header = bytes([font.BASELINE, set_width & 0xFF, set_width >> 8, height,
                    8, 0, (8 + 194) & 0xFF, (8 + 194) >> 8])
    index = b"".join(bytes([o & 0xFF, o >> 8]) for o in offsets)
    return header + index + bytes(data)


def main(argv):
    if len(argv) != 4:
        sys.exit(__doc__)
    blob = build(load(argv[1]))
    lines = ["; Generated by tools/mkfont.py from %s" % os.path.basename(argv[1]),
             "        .export %s" % argv[3],
             '        .segment "IODATA"',
             "%s:" % argv[3]]
    for i in range(0, len(blob), 16):
        lines.append("        .byte " + ", ".join("$%02X" % b for b in blob[i:i + 16]))
    open(argv[2], "w").write("\n".join(lines) + "\n")
    print("font %s: %d bytes" % (argv[3], len(blob)))


if __name__ == "__main__":
    main(sys.argv)
