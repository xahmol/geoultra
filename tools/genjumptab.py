#!/usr/bin/env python3
"""Generate the GEOS jump table ($C100) for the GeoUltra kernal.

Usage: genjumptab.py jumptab.txt OUT.s SOURCE.s [SOURCE.s ...]

jumptab.txt lists the entries in address order (# starts a comment).
Every entry whose name a source exports (.export) becomes `jmp Name`;
an entry written `Name = ($9016)` becomes `jmp ($9016)` (a disk driver
vector), one written `Name = Other` becomes `jmp Other` (another routine); every other entry becomes `jsr Trap` (3 bytes too), which
records the entry's address and halts (src/kernal/info.s).
"""
import re
import sys

EXPORT = re.compile(r"^\s*\.export\s+(.*?)\s*(;.*)?$", re.IGNORECASE)


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    names = [l.split("#")[0].strip() for l in open(argv[1])]
    names = [n for n in names if n]
    vectors = dict(n.replace(" ", "").split("=") for n in names if "=" in n)
    names = [n.split("=")[0].strip() for n in names]
    exported = set()
    for src in argv[3:]:
        for line in open(src):
            m = EXPORT.match(line)
            if m:
                exported.update(s.strip() for s in m.group(1).split(","))
    out = ["; Generated by tools/genjumptab.py from src/kernal/jumptab.txt.",
           "        .import Trap"]
    done = [n for n in names if n in exported and n not in vectors]
    others = [v for v in vectors.values() if not v.startswith("(")]
    if done or others:
        out.append("        .import " + ", ".join(done + others))
    out.append('        .segment "JUMPTAB"')
    for i, n in enumerate(names):
        addr = 0xC100 + 3 * i
        if n in vectors:
            op = "jmp %s" % vectors[n]
        else:
            op = "jmp %s" % n if n in exported else "jsr Trap"
        out.append("        %-20s ; $%04X %s" % (op, addr, n))
    open(argv[2], "w").write("\n".join(out) + "\n")
    print("jump table: %d of %d entries implemented, %d through the disk driver"
          % (len(done) + len(vectors), len(names), len(vectors)))


if __name__ == "__main__":
    main(sys.argv)
